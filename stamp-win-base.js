/* eslint-disable @typescript-eslint/no-var-requires -- build script, CommonJS. */
'use strict';

/**
 * Put the Elixium icon on pkg's Windows base binary, before pkg packages it.
 *
 * pkg inherits the icon and version resource from the Node binary it builds
 * against, so an untouched elixium.exe shows Node's icon and calls itself
 * "Node.js JavaScript Runtime" in its properties.
 *
 * This must happen BEFORE pkg runs, never after. pkg appends its virtual
 * filesystem to the end of the executable and patches the absolute offset of
 * that payload into the binary. rcedit rewrites the resource section and
 * relays the file out, which moves everything after it — the recorded offset
 * then points at nothing. Such a binary still launches and still prints its
 * help, then dies with "Pkg: Error reading from file." the moment it needs a
 * bundled asset. Confirmed by doing it: the web interface vanished from a
 * binary that had contained it minutes earlier.
 *
 * Editing the base first means pkg appends afterwards and computes the offset
 * against the already-stamped file, and nothing touches it again.
 *
 * The remaining trick is getting pkg to accept an edited base. pkg-fetch looks
 * for `fetched-<node>-<platform>-<arch>` first and checks it against a table
 * of known hashes, discarding and redownloading anything that does not match.
 * Only when that misses does it look for `built-…`, which it accepts with no
 * hash check at all — that is the path for a locally compiled Node, and it is
 * the supported way in. So the stamped copy is written as `built-` and the
 * `fetched-` file is removed, otherwise the untouched one wins and the icon
 * silently never appears.
 *
 * A no-op anywhere but Windows: rcedit drives a Win32 executable, and the mac
 * and Linux binaries have no resource section to write to.
 *
 * Usage: node stamp-win-base.js <pkg-target>    e.g. node16-win-x64
 */

const fs = require('fs');
const os = require('os');
const path = require('path');
const {execFileSync} = require('child_process');

if (process.platform !== 'win32') {
  console.log('not Windows — nothing to stamp');
  process.exit(0);
}

const target = process.argv[2] || 'node16-win-x64';
const parsed = /^node(\d+)-(\w+)-(\w+)$/.exec(target);
if (!parsed) {
  console.error(`unrecognised pkg target: ${target}`);
  process.exit(1);
}
const [, nodeMajor, platform, arch] = parsed;

if (platform !== 'win') {
  console.log(`${target} is not a Windows target — nothing to stamp`);
  process.exit(0);
}

const cacheRoot = process.env.PKG_CACHE_PATH || path.join(os.homedir(), '.pkg-cache');
if (!fs.existsSync(cacheRoot)) {
  console.error(`no pkg cache at ${cacheRoot}`);
  console.error('run pkg once first so it downloads a base binary');
  process.exit(1);
}

// The cache is split into pkg-fetch version folders (v3.4, v3.5 …), and the
// exact Node patch version in the filename is whatever pkg chose to fetch.
const fetchedRe = new RegExp(`^fetched-v${nodeMajor}\\..*-${platform}-${arch}$`);
const builtRe = new RegExp(`^built-v${nodeMajor}\\..*-${platform}-${arch}$`);

let fetched = null;
let built = null;
for (const dir of fs.readdirSync(cacheRoot)) {
  const full = path.join(cacheRoot, dir);
  if (!fs.statSync(full).isDirectory()) continue;
  for (const file of fs.readdirSync(full)) {
    if (fetchedRe.test(file)) fetched = path.join(full, file);
    else if (builtRe.test(file)) built = path.join(full, file);
  }
}

if (!fetched && built) {
  // Already stamped by an earlier run; pkg will pick this up.
  console.log(`already stamped: ${path.relative(cacheRoot, built)}`);
  process.exit(0);
}

if (!fetched) {
  console.error(`no base binary for ${target} under ${cacheRoot}`);
  console.error('run pkg once first so it downloads one');
  process.exit(1);
}

const icon = path.join(__dirname, 'desktop', 'build', 'icon.ico');
if (!fs.existsSync(icon)) {
  // Generated by desktop/make-icons.js; only the SVG is committed.
  console.log('icon.ico missing — generating it');
  execFileSync(process.execPath, [path.join(__dirname, 'desktop', 'make-icons.js')], {stdio: 'inherit'});
}

const {version} = require('./package.json');
const destination = path.join(path.dirname(fetched), path.basename(fetched).replace(/^fetched-/, 'built-'));

fs.copyFileSync(fetched, destination);

require('rcedit')(destination, {
  icon,
  'file-version': version,
  'product-version': version,
  'version-string': {
    ProductName: 'Elixium',
    FileDescription: 'Elixium — Deezer and Qobuz music downloader',
    CompanyName: 'Elixium',
    LegalCopyright: 'MIT License',
    OriginalFilename: 'elixium.exe',
  },
})
  .then(() => {
    // Remove the pristine copy, or pkg finds it first and the icon never lands.
    fs.unlinkSync(fetched);
    console.log(`stamped ${path.relative(cacheRoot, destination)} with the Elixium icon and version ${version}`);
    console.log('run pkg again — it will use this base');
  })
  .catch((error) => {
    // Leave the cache as it was rather than half-stamped.
    try {
      fs.unlinkSync(destination);
    } catch {
      /* nothing useful to do */
    }
    console.error('failed to stamp the base binary:', error.message);
    process.exit(1);
  });
